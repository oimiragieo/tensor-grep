"""A RATCHET over the silent-filesystem-loss class in the Python sources.

THE CLASS: a loop walks filesystem entries and accumulates them into a collection that is
later reported as a result. One entry raises ``OSError`` (permission denied, a vanished file,
a disconnected share). A broad ``except`` swallows it and ``continue``s. The loop finishes,
the collection is SMALLER than the universe it claims to describe, and the command exits 0
with no marker. The caller -- almost always an AI agent -- concludes "no callers, safe to
delete" from a result set that was silently truncated.

That is the same defect the Rust-side ratchet pins for directory walks
(``test_native_walk_error_ratchet.py``, task #276). This file is its Python counterpart:
the codebase had a machine-checked census for one language and hand-enumeration for the
other, which is why the unreadable-path family (#276, #283, #284, #286, #288, #291) was
found one site at a time across a dozen separate PRs.

WHAT THIS DOES *NOT* CLAIM. A site in the census is not automatically a bug. Plenty of
best-effort loops are correct to skip an unreadable entry -- a heuristic seed list, an
optional cache probe. The census is the POPULATION that contains the defects, not the defect
list. Its job is the invariant: *the number of silent-loss sites never increases.* Auditing
a site and fixing it lowers the number; adding one without thinking about disclosure raises
it and turns CI red.

HOW A SITE GETS FIXED. Thread a ``_UnreadablePathFlag`` (see ``repo_map.py``) through the
loop, ``record(exc)`` in the handler, and have the caller disclose ``unreadable_paths``
alongside its result -- the shape #276 established and #767/#768/#769/#770 wired into
inventory, docs-coverage, the session snapshot and the validation plan. Then LOWER the count
here in the same PR.

House rule this implements: "model the class, don't enumerate the cases". Round N+1 finding
another instance of a defect family means the answer is an invariant, not another reviewer.

WHERE THAT RULE STOPS -- a near miss worth keeping (#292, 2026-07-26). Several audited-benign
sites share a shape: the handler only ASSIGNS a fallback and lets the loop continue, so nothing
is skipped (``resolved = candidate`` in the doctor PATH scans, ``_nearby_session_roots``). It is
tempting to teach the detector that shape and drop ~20 sites of noise in one edit.

Measuring the shape's distribution before encoding it showed why that would be a disaster:
``checkpoint_store``'s undo commit phase matched it too -- ``removed_bytes = None`` followed by an
``unlink()`` that destroys a file the revert can no longer restore. That was task #297, the most
severe defect this campaign found. A "benign fallback" rule would have excused it FOREVER, in the
exact file where it mattered most.

The lesson generalises: encode a shape only when it is *structurally* incapable of hiding a loss
(a handler that exits the process; one whose accumulator feeds a later ``raise``). "The handler
looks harmless" is not that. Whether a fallback is safe depends on what the loop DOES with the
fallback value afterwards, which is a semantic question this detector deliberately does not try
to answer. Audit those sites and record the verdict instead -- see CONTRACTS.md section 0.
"""

