def _called_names(node: ast.AST) -> set[str]:
    """Every attribute/function name called anywhere under ``node``."""
    return {
        name
        for child in ast.walk(node)
        if isinstance(child, ast.Call)
        and (name := getattr(child.func, "attr", None) or getattr(child.func, "id", None))
    }


def _caught_names(handler: ast.ExceptHandler) -> set[str]:
    exc_type = handler.type
    if exc_type is None:
        return {"BARE"}
    parts = exc_type.elts if isinstance(exc_type, ast.Tuple) else [exc_type]
    return {getattr(p, "attr", None) or getattr(p, "id", None) or "?" for p in parts}


def _terminates(handler: ast.ExceptHandler) -> bool:
    """True when the handler hands control to something that ends the command.

    ``sys.exit`` and this codebase's ``_exit_*`` helpers (e.g. ``_exit_search_error``) raise
    ``SystemExit`` internally, so nothing downstream ever sees a truncated result. The AST shows
    only a call, which read as silence and produced FALSE POSITIVES -- `-f` pattern-file reads
    (main.py) are the clearest case: they already fail loud with exit 2 per the Backend
    Fail-Closed Contract, and the census still counted them.
    """
    return any(
        name == "exit" or name.startswith("_exit_") or name.startswith("exit_")
        for name in _called_names(handler)
    )


def _raised_names(func: ast.AST) -> set[str]:
    """Names mentioned inside any ``raise`` in ``func``.

    Catches the accumulate-then-raise shape: the handler appends the failure to a list and the
    function raises on that list once the loop finishes (``checkpoint_store``'s undo pre-flight
    builds ``missing`` and then raises ``CheckpointCorruptError(..., missing_files=missing)``).
    Handler-local inspection cannot see that, so it counted a DISCLOSURE accumulator as loss.
    """
    names: set[str] = set()
    for node in ast.walk(func):
        if isinstance(node, ast.Raise):
            names |= {n.id for n in ast.walk(node) if isinstance(n, ast.Name)}
    return names


def _is_silent(handler: ast.ExceptHandler, raised_names: set[str]) -> bool:
    """True when the handler neither re-raises, records, terminates, nor feeds a later raise."""
    if any(isinstance(n, ast.Raise) for n in ast.walk(handler)):
        return False
    if _terminates(handler):
        return False
    if _called_names(handler) & _DISCLOSING_CALLS:
        return False
    # `missing.append(rel)` where the enclosing function later raises using `missing`.
    accumulated_into = {
        node.func.value.id
        for node in ast.walk(handler)
        if isinstance(node, ast.Call)
        and isinstance(node.func, ast.Attribute)
        and node.func.attr in _ACCUMULATORS
        and isinstance(node.func.value, ast.Name)
    }
    return not (accumulated_into & raised_names)


def _returned_names(func: ast.AST) -> set[str]:
    """Names mentioned inside any ``return`` in ``func`` (task #807).

    The accumulate-then-RETURN sibling of ``_raised_names``. A handler that appends the failure
    to a list the function RETURNS has disclosed it just as surely as one that raises on it --
    the caller receives the record either way. `_paths_modified_since_checkpoint` is the live
    case: its ``except OSError`` appends to ``unchecked`` and the function returns
    ``(sorted(diverged), sorted(unchecked))``, so undo can report which paths it could not check.

    Without this the census counted that DISCLOSURE as loss, which was not merely a false
    positive -- it made the ratchet unable to DISCRIMINATE at that site. The count was identical
    with the disclosure and with a bare ``continue``, so re-introducing the silent drop kept the
    gate green. Proven by mutation before this was written: the ceiling of 7 protected nothing
    there.

    Deliberately narrow. It is NOT "appends to any list": the accumulator must reach a value the
    function actually hands back. Widening it to any append would excuse every handler stuffing a
    list nobody reads, which is exactly the loss this census exists to find -- and is why the
    ceiling was raised to 7 rather than the detector loosened at the time.
    """
    names: set[str] = set()
    for node in ast.walk(func):
        if isinstance(node, ast.Return) and node.value is not None:
            names |= {n.id for n in ast.walk(node.value) if isinstance(n, ast.Name)}
    return names


def _enclosing_raised_names(tree: ast.AST) -> dict[int, set[str]]:
    """Map each loop node's id() to the DISCLOSED names of the function that contains it.

    "Disclosed" = raised on OR returned. Both hand the record to the caller; a handler feeding
    either one is reporting the failure, not swallowing it.
    """
    mapping: dict[int, set[str]] = {}
    for func in ast.walk(tree):
        if not isinstance(func, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        disclosed = _raised_names(func) | _returned_names(func)
        if not disclosed:
            continue
        for node in ast.walk(func):
            if isinstance(node, (ast.For, ast.While, ast.AsyncFor)):
                mapping[id(node)] = mapping.get(id(node), set()) | disclosed
    return mapping


def _silent_loss_lines(source: str) -> list[int]:
    """Line numbers of silent-loss sites in ``source``.

    A site is: a broad ``except`` that discloses nothing -- no re-raise, no log/record, no exit,
    and no accumulator the enclosing function later raises on -- guarding a ``try`` body that
    touches the filesystem, nested inside a loop whose body accumulates or yields.
    """
    tree = ast.parse(source)
    raised_by_loop = _enclosing_raised_names(tree)
    found: list[int] = []
    for loop in ast.walk(tree):
        if not isinstance(loop, (ast.For, ast.While, ast.AsyncFor)):
            continue
        accumulates = bool(_called_names(loop) & _ACCUMULATORS) or any(
            isinstance(n, (ast.Yield, ast.YieldFrom)) for n in ast.walk(loop)
        )
        if not accumulates:
            continue
        for try_node in ast.walk(loop):
            if not isinstance(try_node, ast.Try):
                continue
            # Only the try BODY counts: an fs call inside the handler itself (a cleanup
            # probe) does not mean the guarded operation was a filesystem read.
            if not any(_called_names(stmt) & _FS_CALLS for stmt in try_node.body):
                continue
            raised = raised_by_loop.get(id(loop), set())
            found.extend(
                h.lineno
                for h in try_node.handlers
                if (_caught_names(h) & _BROAD_EXCEPTIONS) and _is_silent(h, raised)
            )
    return found


def _census() -> dict[str, int]:
    """Count silent-loss sites per Python source file under ``src/tensor_grep``."""
    found: dict[str, int] = {}
    for path in sorted(PY_SRC.rglob("*.py")):
        hits = _silent_loss_lines(path.read_text(encoding="utf-8", errors="replace"))
        if hits:
            found[path.name] = len(hits)
    return found


@pytest.mark.skipif(not PY_SRC.is_dir(), reason="src/tensor_grep absent")
def test_no_new_files_start_losing_entries_silently() -> None:
    """A file not in the census must not introduce the idiom.

    This is the arm that bites on new code: a fresh ``except OSError: continue`` inside a
    result-building loop, in a file nobody has audited, is exactly how a command starts
    reporting success over a smaller universe.
    """
    unexpected = sorted(set(_census()) - set(KNOWN_SILENT_LOSS_SITES))
    assert not unexpected, (
        "these files newly swallow a filesystem error inside a loop that accumulates a "
        f"reported result, so a truncated result looks complete: {unexpected}. Thread an "
        "_UnreadablePathFlag through the loop and disclose `unreadable_paths` (see "
        "inventory.py / docs_coverage.py for the shape), or add the file to "
        "KNOWN_SILENT_LOSS_SITES with a reason if the loop genuinely makes no completeness "
        "claim."
    )


@pytest.mark.skipif(not PY_SRC.is_dir(), reason="src/tensor_grep absent")
def test_known_silent_loss_sites_never_grow() -> None:
    """Each audited file's count may FALL (a fix) but never RISE (a regression)."""
    census = _census()
    grew = {
        name: (census.get(name, 0), expected)
        for name, expected in KNOWN_SILENT_LOSS_SITES.items()
        if census.get(name, 0) > expected
    }
    assert not grew, (
        "the silent-loss count ROSE in these files (actual, allowed): "
        f"{grew}. Every added site is a new way for an incomplete result to report success."
    )

    shrank = {
        name: (census.get(name, 0), expected)
        for name, expected in KNOWN_SILENT_LOSS_SITES.items()
        if census.get(name, 0) < expected
    }
    assert not shrank, (
        "sites were FIXED but the ratchet was not lowered (actual, recorded): "
        f"{shrank}. Update KNOWN_SILENT_LOSS_SITES to the new counts so the ratchet keeps "
        "its teeth -- leaving it high would let a future regression slip back in unnoticed."
    )


@pytest.mark.skipif(not PY_SRC.is_dir(), reason="src/tensor_grep absent")
def test_the_detector_actually_discriminates() -> None:
    """ORACLE CHECK -- prove the detector bites before trusting either arm above.

    Without this, a detector that matched nothing would find zero sites everywhere, both
    ratchet arms would pass, and this file would silently certify a codebase it never
    inspected. A check that passes when the thing it guards is broken is not a check.
    (Verification-oracle family, form: the FIXTURE never applied.)

    The negative arms matter as much as the positive one: if a DISCLOSED handler still
    counted, fixing a site would not lower the number and the ratchet could never reach zero.
    """
    silent = """
for path in paths:
    try:
        out.append(path.stat().st_size)
    except OSError:
        continue
"""
    assert _silent_loss_lines(silent) == [5], "detector missed a plain silent-loss site"

    recorded = """
for path in paths:
    try:
        out.append(path.stat().st_size)
    except OSError as exc:
        unreadable.record(exc)
        continue
"""
    assert not _silent_loss_lines(recorded), "a handler that RECORDS must not count as silent"

    reraised = """
for path in paths:
    try:
        out.append(path.stat().st_size)
    except OSError as exc:
        raise BackendExecutionError(str(exc)) from exc
"""
    assert not _silent_loss_lines(reraised), "a handler that RE-RAISES must not count as silent"

    narrow = """
for path in paths:
    try:
        out.append(path.stat().st_size)
    except UnicodeDecodeError:
        continue
"""
    assert not _silent_loss_lines(narrow), (
        "a NARROW exception unrelated to filesystem availability must not count -- widening "
        "the detector to it would bury the real signal in noise"
    )

    no_claim = """
for path in paths:
    try:
        probe(path.stat())
    except OSError:
        continue
"""
    assert not _silent_loss_lines(no_claim), (
        "a loop that accumulates NOTHING makes no completeness claim and must not count"
    )

    # The two shapes the detector learned to forgive. Each needs BOTH arms: teaching it that
    # `_exit_*` and accumulate-then-raise are disclosure is exactly how a detector starts
    # under-reporting, so the near-miss must still count.
    terminates = """
for path in paths:
    try:
        out.append(path.stat().st_size)
    except OSError as exc:
        _exit_search_error("read_error", str(exc), json_mode=False, exit_code=2)
"""
    assert not _silent_loss_lines(terminates), (
        "a handler that EXITS the command cannot hand anyone a truncated result"
    )

    accumulate_then_raise = """
def check(paths):
    missing = []
    for path in paths:
        try:
            path.stat()
        except OSError:
            missing.append(path)
    if missing:
        raise CheckpointCorruptError("corrupt", missing_files=missing)
"""
    assert not _silent_loss_lines(accumulate_then_raise), (
        "appending to a list the function then RAISES on is disclosure, not loss"
    )

    accumulate_never_raised = """
def check(paths):
    missing = []
    kept = []
    for path in paths:
        try:
            kept.append(path.stat().st_size)
        except OSError:
            missing.append(path)
    if not kept:
        raise ValueError("empty")
    return kept
"""
    assert _silent_loss_lines(accumulate_never_raised), (
        "NEAR MISS: the function raises, but on `kept` -- `missing` is collected and thrown "
        "away, so the loss IS silent. If this stops counting, the raise-name check has "
        "widened into 'any raise anywhere excuses the whole function'."
    )

    # And the census must be non-empty: if it were, the two ratchet arms would pass
